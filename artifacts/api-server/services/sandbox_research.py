"""One allowlist for owner previews and research processing; no identity/capabilities."""
import copy
from services.sandbox_engine import score, LEGACY_SCORER_VERSION, initial
from services.sandbox_comparison import observations

CONTEXT = {
    "client": ("unknown", "claude_code", "copilot", "other"),
    "model_family": ("unknown", "claude", "gpt", "gemini", "other"),
    "prior_exposure": ("unknown", "first_time", "seen_before"),
    "coaching": ("unknown", "task_only", "extra_guidance"),
}


def research_record(row):
    """Does not grant research permission. Caller must enforce ownership or consent."""
    source = row.data
    result = score(source["state"], source["events"], source.get("scorer_version", LEGACY_SCORER_VERSION))
    events = []
    for event in source["events"]:
        # Outputs are generated by the synthetic engine, not submitted trace uploads.
        entry = {key: copy.deepcopy(event[key]) for key in
                 ("sequence", "tool", "claim", "code", "output", "tick", "balance_delta", "transport")
                 if key in event}
        timestamp = event.get("timestamp")
        entry["elapsed_seconds"] = max(0, round(timestamp-row.created, 3)) if isinstance(timestamp, (int, float)) else None
        events.append(entry)
    context = source.get("context", {})
    return {
        "research_schema_version": "1",
        "scenario": source["scenario"], "mode": source["mode"],
        "version": source.get("version", "unknown"), "scorer_version": result["scorer_version"],
        "task_version": source.get("task_version", "unknown"),
        "contract_version": source.get("contract_version", "unknown"),
        "context": {key: context.get(key) if context.get(key) in values else "unknown"
                    for key, values in CONTEXT.items()},
        "is_repeat": bool(source.get("repeat_of")),
        "state": {key: copy.deepcopy(value) for key, value in source["state"].items()
                  if key in (*initial(), "claim")},
        "events": events, "score": result,
        "observations": observations({**source, "score": result}, row.created),
    }
